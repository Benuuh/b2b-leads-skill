"""原始记录信封（spec b2b-leads-2.6 §3.1.5）。

独立密钥 ``PROSPECT_SOURCE_RAW_ENVELOPE_SECRET``，不与其他密钥混用。
用途：审计时还原"当时源里给的是什么"，平时不读；解密只发生在
``--explain`` 且经人确认之后。

实现（仅标准库）：HMAC-SHA256 派生子密钥 + CTR 式 keystream + encrypt-then-MAC。
格式：``b'PSV1' + 16 字节 nonce + ciphertext + 32 字节 tag``。

硬规矩 #3：解密失败不抛异常，返回状态字典：
``{'status': 'undecryptable', 'reason': 'key_mismatch' | 'tampered', ...}``，
原密文保留，批处理记 ``envelope_undecryptable`` 后继续，不中断整批。

开发降级（§3.5）：缺密钥时明文存储，前缀 ``b'PSPLAIN:'`` 标记，并打
``dev-insecure`` 标记。
"""
from __future__ import annotations

import hashlib
import hmac
import json
import os

MAGIC = b'PSV1'
PLAIN_PREFIX = b'PSPLAIN:'
NONCE_BYTES = 16
TAG_BYTES = 32
BLOCK = 32

SECRET_ENV = 'PROSPECT_SOURCE_RAW_ENVELOPE_SECRET'


class EnvelopeSecretUnavailable(RuntimeError):
    """生产环境缺密钥；启动校验（secrets.validate_startup_secrets）更早拦截。"""


def _secret():
    value = os.getenv(SECRET_ENV, '').strip()
    if not value:
        raise EnvelopeSecretUnavailable('缺少 ' + SECRET_ENV)
    return value.encode('utf-8')


def _keystream(key: bytes, nonce: bytes, length: int) -> bytes:
    # Track generated bytes incrementally: re-summing every block would make a
    # B-block payload O(B^2). The output bytes are unchanged.
    blocks = []
    generated = 0
    counter = 0
    while generated < length:
        block = hmac.new(key, nonce + counter.to_bytes(8, 'big'), hashlib.sha256).digest()
        blocks.append(block)
        generated += len(block)
        counter += 1
    return b''.join(blocks)[:length]


def _mac(mac_key: bytes, nonce: bytes, ciphertext: bytes) -> bytes:
    return hmac.new(mac_key, nonce + ciphertext, hashlib.sha256).digest()


def seal(payload: dict, *, secret: str | None = None) -> tuple[str, str, str]:
    """返回 (ciphertext_b64, sha256_hex, mode)；mode 为 'encrypted' 或 'plaintext'。"""
    import base64
    plain = json.dumps(payload, ensure_ascii=False, sort_keys=True).encode('utf-8')
    value = secret if secret is not None else os.getenv(SECRET_ENV, '').strip()
    if value:
        key = value.encode('utf-8') if isinstance(value, str) else value
        enc_key = hmac.new(key, b'PSV1-enc', hashlib.sha256).digest()
        mac_key = hmac.new(key, b'PSV1-mac', hashlib.sha256).digest()
        nonce = os.urandom(NONCE_BYTES)
        ciphertext = bytes(a ^ b for a, b in zip(plain, _keystream(enc_key, nonce, len(plain))))
        blob = MAGIC + nonce + ciphertext + _mac(mac_key, nonce, ciphertext)
        mode = 'encrypted'
    else:
        blob = PLAIN_PREFIX + plain
        mode = 'plaintext'
    return base64.b64encode(blob).decode('ascii'), hashlib.sha256(blob).hexdigest(), mode


def open_envelope(ciphertext_b64: str, *, secret: str | None = None) -> dict:
    """解密信封。任何失败返回状态字典，绝不抛异常（硬规矩 #3）。"""
    import base64
    try:
        blob = base64.b64decode(str(ciphertext_b64), validate=True)
    except Exception:
        return {'status': 'undecryptable', 'reason': 'corrupt_encoding'}
    if blob.startswith(PLAIN_PREFIX):
        try:
            return {'status': 'ok', 'mode': 'plaintext',
                    'payload': json.loads(blob[len(PLAIN_PREFIX):].decode('utf-8'))}
        except Exception:
            return {'status': 'undecryptable', 'reason': 'corrupt_payload'}
    if len(blob) < len(MAGIC) + NONCE_BYTES + TAG_BYTES or not blob.startswith(MAGIC):
        return {'status': 'undecryptable', 'reason': 'unknown_format'}
    try:
        value = secret if secret is not None else os.getenv(SECRET_ENV, '')
        if not value:
            # 无密钥可试：与密钥不匹配等价，绝不明文兜底。
            return {'status': 'undecryptable', 'reason': 'key_mismatch'}
        key = value.encode('utf-8')
        nonce = blob[len(MAGIC):len(MAGIC) + NONCE_BYTES]
        ciphertext = blob[len(MAGIC) + NONCE_BYTES:-TAG_BYTES]
        expected = blob[-TAG_BYTES:]
        mac_key = hmac.new(key, b'PSV1-mac', hashlib.sha256).digest()
        if not hmac.compare_digest(_mac(mac_key, nonce, ciphertext), expected):
            return {'status': 'undecryptable', 'reason': 'key_mismatch', 'envelope_sha256':
                    hashlib.sha256(blob).hexdigest()}
        enc_key = hmac.new(key, b'PSV1-enc', hashlib.sha256).digest()
        plain = bytes(a ^ b for a, b in zip(ciphertext, _keystream(enc_key, nonce, len(ciphertext))))
        return {'status': 'ok', 'mode': 'encrypted', 'payload': json.loads(plain.decode('utf-8'))}
    except Exception:
        return {'status': 'undecryptable', 'reason': 'corrupt_payload'}
